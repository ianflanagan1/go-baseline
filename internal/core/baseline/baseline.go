// Verify returns each way the project differs from the baseline, or nil when
// it matches.
func Verify(p Project) ([]string, error) {
	module, err := ModulePath(p.GoMod)
	if err != nil {
		return nil, err
	}
	if p.Golangci == nil {
		return []string{".golangci.yml is missing; run `go tool go-baseline write`"}, nil
	}
	want, err := GolangciConfig(module)
	if err != nil {
		return nil, err
	}
	var problems []string
	if !bytes.Equal(p.Golangci, want) {
		problems = append(problems, ".golangci.yml differs from the baseline; run `go tool go-baseline write`")
	}
	switch {
	case p.Guide == nil:
		problems = append(problems, "BASELINE.md is missing; run `go tool go-baseline write`")
	case !bytes.Equal(p.Guide, guide):
		problems = append(problems, "BASELINE.md differs from the baseline; run `go tool go-baseline write`")
	}
	switch {
	case p.Workflow == nil:
		problems = append(problems, WorkflowPath+" is missing; run `go tool go-baseline write`")
	case !bytes.Equal(p.Workflow, workflow):
		problems = append(problems, WorkflowPath+" differs from the baseline; run `go tool go-baseline write`")
	}
	switch {
	case p.Taskfile == nil:
		problems = append(problems, TaskfilePath+" is missing; run `go tool go-baseline write`")
	case !bytes.Equal(p.Taskfile, taskfile):
		problems = append(problems, TaskfilePath+" differs from the baseline; run `go tool go-baseline write`, and put the project's own tasks in Taskfile.project.yml")
	}
	problems = append(problems, devboxProblems(p.Devbox, p.GoMod)...)
	problems = append(problems, gitignoreProblems(p.Gitignore)...)
	problems = append(problems, layoutProblems(p.Dirs)...)
	problems = append(problems, RolelessProblems(module, p.Packages)...)
	problems = append(problems, DependencyProblems(module, p.Packages)...)
	return problems, nil
}

func devboxProblems(devbox, goMod []byte) []string {
	if devbox == nil {
		return []string{"devbox.json is missing"}
	}
	var config struct {
		Packages []string          `json:"packages"`
		Env      map[string]string `json:"env"`
		Shell    struct {
			Scripts map[string]json.RawMessage `json:"scripts"`
		} `json:"shell"`
	}
	if err := json.Unmarshal(devbox, &config); err != nil {
		return []string{fmt.Sprintf("devbox.json can't be read as a list of packages, string env and scripts: %v", err)}
	}

	problems := devboxPackageProblems(config.Packages)
	problems = append(problems, goVersionProblems(config.Packages, goMod)...)
	if config.Env["GOTOOLCHAIN"] != "local" {
		problems = append(problems, `devbox.json must set env GOTOOLCHAIN to "local"`)
	}
	for _, name := range slices.Sorted(maps.Keys(config.Shell.Scripts)) {
		problems = append(problems, fmt.Sprintf("devbox.json script %q: move it into a task in Taskfile.project.yml; devbox only pins tools", name))
	}
	return problems
}

func devboxPackageProblems(packages []string) []string {
	var problems []string
	if !slices.ContainsFunc(packages, exactGo.MatchString) {
		problems = append(problems, "devbox.json must pin Go to an exact version, such as go@1.27.3")
	}
	if !slices.Contains(packages, "golangci-lint@"+GolangciLintVersion) {
		problems = append(problems, "devbox.json must pin golangci-lint@"+GolangciLintVersion)
	}
	if !slices.Contains(packages, "go-task@"+TaskVersion) {
		problems = append(problems, "devbox.json must pin go-task@"+TaskVersion+", which runs the Taskfile")
	}
	if !slices.Contains(packages, CoupledTagsLintPackage) {
		problems = append(problems, "devbox.json must have "+CoupledTagsLintPackage+", which check runs to lint the COUPLED tags; add it with `devbox add "+CoupledTagsLintPackage+"`")
	}
	return problems
}

// gitignoreProblems reports a .gitignore that doesn't ignore the cache
// directory with CacheIgnore. Git ignores trailing spaces, and the line may
// end with a carriage return.
func gitignoreProblems(gitignore []byte) []string {
	if gitignore == nil {
		return []string{".gitignore is missing; add one with the line " + CacheIgnore + ", for the directory tools keep their caches in"}
	}
	for line := range strings.Lines(string(gitignore)) {
		if strings.TrimRight(line, " \r\n") == CacheIgnore {
			return nil
		}
	}
	return []string{".gitignore must have the line " + CacheIgnore + ", for the directory tools keep their caches in"}
}

// goVersionProblems reports go.mod's go line differing from the minor
// version of the Go that devbox pins. A missing pin is reported by
// devboxPackageProblems.
func goVersionProblems(packages []string, goMod []byte) []string {
	var minor string
	for _, pkg := range packages {
		if match := exactGo.FindStringSubmatch(pkg); match != nil {
			minor = match[1]
		}
	}
	if minor == "" {
		return nil
	}
	goLine, found := goDirective(goMod)
	if !found {
		return []string{"go.mod has no go line; run `devbox run -- go mod edit -go=" + minor + "`"}
	}
	if goLine != minor && !strings.HasPrefix(goLine, minor+".") {
		return []string{fmt.Sprintf("go.mod's go line is %s, but devbox.json pins Go %s; run `devbox run -- go mod edit -go=%s`", goLine, minor, minor)}
	}
	return nil
}

// goDirective returns the version on go.mod's go line, and whether it has one.
func goDirective(goMod []byte) (string, bool) {
	for line := range strings.Lines(string(goMod)) {
		fields := strings.Fields(strings.SplitN(line, "//", 2)[0])
		if len(fields) == 2 && fields[0] == "go" {
			return fields[1], true
		}
	}
	return "", false
}

func layoutProblems(dirs []string) []string {
	var problems []string
	for _, dir := range dirs {
		switch base := path.Base(dir); {
		case dir == "src" || dir == "pkg":
			problems = append(problems, fmt.Sprintf("%s/: no src/ or pkg/ directories; see https://go.dev/doc/modules/layout", dir))
		case base == "util" || base == "common" || base == "helpers":
			problems = append(problems, fmt.Sprintf("%s/: name the package for what it provides, not %q", dir, base))
		}
	}
	return problems
}

// HasEntrypoint reports whether the module has a program in cmd/. packages
// are from `go list -json`.
func HasEntrypoint(module string, packages []Package) bool {
	return slices.ContainsFunc(sortedOwnPackages(module, packages), func(p Package) bool {
		role, _ := RoleOf(relativeDir(module, p.ImportPath))
		return role == Entrypoint
	})
}

// DeadcodeFilter is the -filter that limits deadcode to module's packages
// under cmd/ and internal/. Other modules may import any of its other
// packages, so a function no program in cmd/ calls may still be in use.
func DeadcodeFilter(module string) string {
	return "^" + regexp.QuoteMeta(module) + "/(cmd|internal)(/|$)"
}

// DependencyProblems reports each third-party package that a core or
// orchestrator package depends on, directly or through other packages, and that imports
// an I/O package. The standard library is trusted: depguard checks the
// module's own imports of it, and its pure packages import os themselves.
func DependencyProblems(module string, packages []Package) []string {
	r := reach{module: module, byPath: packagesByPath(packages), from: map[string]string{}}
	for _, p := range sortedOwnPackages(module, packages) {
		if role, _ := RoleOf(relativeDir(module, p.ImportPath)); role != Core && role != Orchestrator {
			continue
		}
		for _, imported := range p.Imports {
			r.walk(imported, p.ImportPath)
		}
	}
	return r.ioProblems()
}

// reach finds the third-party packages the module's packages depend on.
// from maps each to the first of the module's packages found to depend on
// it.
type reach struct {
	module string
	byPath map[string]Package
	from   map[string]string
}

func (r reach) walk(importPath, from string) {
	p, ok := r.byPath[importPath]
	if !ok || !isThirdParty(p, r.module) {
		return
	}
	if _, seen := r.from[importPath]; seen {
		return
	}
	r.from[importPath] = from
	for _, imported := range p.Imports {
		r.walk(imported, from)
	}
}

// ioProblems reports each I/O import of a package reached, leaving out the
// allowlist.
func (r reach) ioProblems() []string {
	var problems []string
	allowed := dependencyAllowlist()
	for _, importPath := range slices.Sorted(maps.Keys(r.from)) {
		if _, ok := allowed[importPath]; ok {
			continue
		}
		for _, imported := range r.byPath[importPath].Imports {
			if IsIO(imported) {
				problems = append(problems, fmt.Sprintf(
					"%s depends on %s, which imports %s; the core and orchestrators can't depend on I/O, even indirectly",
					r.from[importPath], importPath, imported))
			}
		}
	}
	return problems
}

// DeadcodeProblems turns the output of deadcode, one unreachable function
// per line, into problems.
func DeadcodeProblems(output []byte) []string {
	var problems []string
	for line := range strings.Lines(string(output)) {
		if line = strings.TrimSpace(line); line != "" {
			problems = append(problems, line+"; no program in cmd/ calls it, even indirectly: delete it, or call it")
		}
	}
	return problems
}

// ParseCoverage reads `go test -cover` output and returns each package's
// statement coverage, in percent. Packages without statements are left out.
func ParseCoverage(output []byte) map[string]float64 {
	coverage := map[string]float64{}
	for line := range strings.Lines(string(output)) {
		match := coverageLine.FindStringSubmatch(line)
		if match == nil {
			continue
		}
		if percent, err := strconv.ParseFloat(match[2], 64); err == nil {
			coverage[match[1]] = percent
		}
	}
	return coverage
}

// CoverageProblems reports each core package whose coverage is below
// MinCoreCoverage. packages are the module's own, from `go list -json ./...`.
func CoverageProblems(module string, packages []Package, coverage map[string]float64) []string {
	var problems []string
	for _, p := range sortedOwnPackages(module, packages) {
		if role, _ := RoleOf(relativeDir(module, p.ImportPath)); role != Core {
			continue
		}
		if percent, ok := coverage[p.ImportPath]; ok && percent < MinCoreCoverage {
			problems = append(problems, fmt.Sprintf(
				"%s: core coverage is %.1f%%; it must be at least %.0f%%", p.ImportPath, percent, MinCoreCoverage))
		}
	}
	return problems
}

func packagesByPath(packages []Package) map[string]Package {
	byPath := make(map[string]Package, len(packages))
	for _, p := range packages {
		byPath[p.ImportPath] = p
	}
	return byPath
}

func isThirdParty(p Package, module string) bool {
	return !p.Standard && !isOwn(p, module)
}

func isOwn(p Package, module string) bool {
	return !p.Standard && p.Module != nil && p.Module.Path == module
}

func sortedOwnPackages(module string, packages []Package) []Package {
	var own []Package
	for _, p := range packages {
		if isOwn(p, module) {
			own = append(own, p)
		}
	}
	slices.SortFunc(own, func(a, b Package) int { return strings.Compare(a.ImportPath, b.ImportPath) })
	return own
}

func relativeDir(module, importPath string) string {
	if importPath == module {
		return ""
	}
	return strings.TrimPrefix(importPath, module+"/")
}
